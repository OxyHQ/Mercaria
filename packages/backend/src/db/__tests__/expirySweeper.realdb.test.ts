/**
 * A guest session with caller-supplied lifecycle timestamps (ADR 0003 D11).
 *
 * The `tokenHash` is a synthetic unique marker, never a real token's hash —
 * what is under test is the purge predicate, and the resolver is not in play.
 */
async function makeGuestSessionRow(input: {
  expiresAt: Date;
  revokedAt?: Date;
}): Promise<string> {
  const [row] = await db
    .insert(guestSessions)
    .values({
      tokenHash: `sweep-guest-${uuidv7()}`,
      clientClass: 'other',
      lastSeenAt: new Date(),
      expiresAt: input.expiresAt,
      ...(input.revokedAt === undefined ? {} : { revokedAt: input.revokedAt }),
    })
    .returning({ id: guestSessions.id });
  guestSessionIds.push(row.id);
  return row.id;
}

async function guestSessionExists(id: string): Promise<boolean> {
  const rows = await db
    .select({ id: guestSessions.id })
    .from(guestSessions)
    .where(eq(guestSessions.id, id));
  return rows.length === 1;
}

/**
 * A referral touch with a caller-supplied deadline (#142). The touch's own
 * CHECK orders `occurred < window expiry <= expires`, so both fixture shapes
 * derive the earlier two from the deadline rather than from "now".
 */
async function makeReferralTouchRow(expiresAt: Date): Promise<string> {
  if (touchChain === null) {
    const [program] = await db
      .insert(referralPrograms)
      .values({
        programId: `sweep-prog-${uuidv7()}`,
        version: 1,
        name: 'Sweep fixture program',
        description: 'fixture',
        publicTermsSummary: 'fixture',
        family: 'buyer_referral',
        eligiblePartnerTypes: ['user'],
        eligibleSubjectKinds: ['oxy_user'],
        attributionPolicy: 'last_touch',
        attributionWindowDays: 30,
        qualifyingEventPolicy: 'first_qualifying_paid_order',
        commissionRuleRef: 'sweep-rule',
        holdDays: 60,
        payoutPolicyRef: 'sweep-payout',
        termsVersion: 't1',
        disclosureVersion: 'd1',
        createdByOxyUserId: `sweep-op-${uuidv7()}`,
      })
      .returning({ id: referralPrograms.id });
    const [partner] = await db
      .insert(referralPartners)
      .values({
        ownerType: 'user',
        ownerId: `sweep-partner-${uuidv7()}`,
        displayName: 'Sweep partner',
        state: 'approved',
        approvedAt: new Date(),
      })
      .returning({ id: referralPartners.id });
    const [code] = await db
      .insert(referralCodes)
      .values({
        partnerId: partner.id,
        programVersionId: program.id,
        code: `swp-${uuidv7().replace(/-/g, '').slice(0, 20)}`,
      })
      .returning({ id: referralCodes.id });
    touchChain = { programVersionId: program.id, partnerId: partner.id, codeId: code.id };
  }
  const [row] = await db
    .insert(referralTouches)
    .values({
      programVersionId: touchChain.programVersionId,
      partnerId: touchChain.partnerId,
      codeId: touchChain.codeId,
      touchKind: 'code_entry_in_app',
      occurredAt: new Date(expiresAt.getTime() - 2 * 60 * 60 * 1_000),
      clientSurface: 'web',
      actorKind: 'oxy_user',
      oxyUserId: `sweep-toucher-${uuidv7()}`,
      consentMode: 'granted',
      attributionWindowExpiresAt: new Date(expiresAt.getTime() - 60 * 60 * 1_000),
      expiresAt,
    })
    .returning({ id: referralTouches.id });
  touchIds.push(row.id);
  return row.id;
}


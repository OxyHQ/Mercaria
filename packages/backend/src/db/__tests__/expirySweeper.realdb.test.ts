let db: Database;

/** An hour in the past — comfortably past any `expires_at` deadline. */
const EXPIRED_AT = new Date(Date.now() - 60 * 60 * 1_000);
/** An hour in the future — comfortably short of one. */
const NOT_YET_EXPIRED_AT = new Date(Date.now() + 60 * 60 * 1_000);
/**
 * `available_at` for every outbox fixture: an hour ahead, so no fixture is ever
 * DUE. The sweep selects on `expires_at` alone, so this changes nothing under
 * test — but the database is shared and vitest runs files in parallel, and a
 * sibling file's dispatcher-style claim (`moderation-writes.realdb.test.ts`
 * claims without an event id) selects on `status = 'pending' AND available_at <=
 * now`. A due fixture here is claimable there, and a `sweep-outbox-*` id has
 * surfaced inside that file's claim assertions (#151). Never-due fixtures cannot
 * cross that predicate, whatever new claim-shaped test a sibling grows.
 */
const NEVER_DUE_AT = NOT_YET_EXPIRED_AT;
/** 91 days ago: one day past the dismissed-notification retention. */
const PAST_NOTIFICATION_RETENTION = new Date(Date.now() - 91 * 24 * 60 * 60 * 1_000);
/** 8 days ago: one day past the guest-session 7-day purge grace (ADR 0003 D11). */
const PAST_GUEST_PURGE_GRACE = new Date(Date.now() - 8 * 24 * 60 * 60 * 1_000);
/** 1 day ago: expired/revoked, but still INSIDE the 7-day purge grace. */
const WITHIN_GUEST_PURGE_GRACE = new Date(Date.now() - 24 * 60 * 60 * 1_000);

const outboxIds: string[] = [];
const eventIds: string[] = [];
const notificationUserIds: string[] = [];
const paymentOutboxIds: string[] = [];
/** Tracked by `provider_event_id`: the row's own id is generated by the table. */
const providerEventIds: string[] = [];
const guestSessionIds: string[] = [];
const touchIds: string[] = [];
/** The one code/partner/program-version chain every touch fixture hangs off. */
let touchChain: { programVersionId: string; partnerId: string; codeId: string } | null = null;

/**
 * An outbox row with a caller-supplied deadline.
 *
 * The id is minted per row rather than derived, unlike production's deterministic
 * `moderation:report.submit:<id>`: what is under test is the sweep, and two tests
 * converging on one row would make a deletion look like a survival.
 */
async function makeOutboxRow(expiresAt: Date): Promise<string> {
  const id = `sweep-outbox-${uuidv7()}`;
  outboxIds.push(id);
  await db.insert(moderationOutboxes).values({
    id,
    kind: 'report.submit',
    payload: { reportId: uuidv7() },
    status: 'pending',
    attempts: 0,
    availableAt: NEVER_DUE_AT,
    expiresAt,
  });
  return id;
}

async function makeEventClaim(expiresAt: Date): Promise<string> {
  const id = `sweep-event-${uuidv7()}`;
  eventIds.push(id);
  await db.insert(moderationEvents).values({
    id,
    eventType: 'webhook',
    claimedAt: new Date(),
    expiresAt,
  });
  return id;
}

async function makeNotification(dismissedAt: Date | null): Promise<string> {
  const oxyUserId = `sweep-notif-${uuidv7()}`;
  notificationUserIds.push(oxyUserId);
  const [row] = await db
    .insert(notifications)
    .values({
      oxyUserId,
      type: 'order_placed',
      title: 'Order placed',
      body: 'Your order has been placed.',
      channels: ['in_app'],
      deliveryStatus: { in_app: 'sent' },
      // The CHECK ties these two together, so a dismissed fixture must set both.
      status: dismissedAt === null ? 'sent' : 'dismissed',
      priority: 'normal',
      ...(dismissedAt === null ? {} : { dismissedAt }),
    })
    .returning({ id: notifications.id });
  return row.id;
}


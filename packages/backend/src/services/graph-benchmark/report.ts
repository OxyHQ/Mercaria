/**
 * Rendering a benchmark run as the markdown that lands in `docs/performance/`.
 *
 * Pure, and separate from the runner, for one reason: the report is the
 * DELIVERABLE and the runner is the instrument. A number that reached the
 * document without passing the vacuity floors would be a claim nobody measured,
 * so {@link renderReport} refuses to render at all while a floor is unmet — the
 * refusal is a rendered document that says which shape measured nothing, not a
 * silent omission and not a smaller table.
 */

import type { BenchmarkResult, ShapeMeasurement } from './runner.js';

function formatBytes(bytes: number): string {
  if (bytes >= 1_073_741_824) return `${(bytes / 1_073_741_824).toFixed(2)} GB`;
  if (bytes >= 1_048_576) return `${(bytes / 1_048_576).toFixed(1)} MB`;
  if (bytes >= 1_024) return `${(bytes / 1_024).toFixed(0)} kB`;
  return `${String(bytes)} B`;
}

function ms(value: number): string {
  return value >= 100 ? value.toFixed(1) : value.toFixed(3);
}

function shapeRow(measurement: ShapeMeasurement): string {
  const label =
    measurement.statementCount > 1
      ? `${measurement.shapeId}.${String(measurement.statementIndex + 1)}`
      : measurement.shapeId;
  const amplification =
    measurement.analysis.rowsReturned === 0
      ? 'n/a'
      : (measurement.analysis.rowsScanned / measurement.analysis.rowsReturned).toFixed(1);
  return [
    `| ${label}`,
    measurement.title,
    ms(measurement.latency.p50Ms),
    ms(measurement.latency.p95Ms),
    ms(measurement.latency.p99Ms),
    ms(measurement.analysis.executionTimeMs),
    String(measurement.analysis.rowsScanned),
    String(measurement.analysis.rowsReturned),
    amplification,
    measurement.analysis.indexNames.join(', ') || '(none)',
    ' |',
  ].join(' | ');
}

const SHAPE_TABLE_HEADER = [
  '| Shape | Read | p50 ms | p95 ms | p99 ms | plan exec ms | rows scanned | rows returned | scan/return | index used |',
  '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |',
].join('\n');

/** Everything that made a run's numbers meaningless, across all its shapes. */
export function collectViolations(result: BenchmarkResult): string[] {
  return [...result.floorViolations, ...result.shapes.flatMap((shape) => [...shape.violations])];
}

export function renderReport(result: BenchmarkResult): string {
  const violations = collectViolations(result);
  const lines: string[] = [];

  lines.push(`# Canonical graph query plans — scale \`${result.scale.name}\``);
  lines.push('');
  lines.push(
    'Generated by `packages/backend/scripts/graph-query-benchmark.ts`. Every number below ' +
      'was measured; nothing is estimated. Re-generate with the command in ' +
      '`docs/performance/README.md` — the dataset is deterministic, so a re-run on the same ' +
      'hardware reproduces these figures.',
  );
  lines.push('');
  lines.push(`- Server: \`${result.postgresVersion}\``);
  lines.push(`- Measured: ${result.measuredAt}`);
  lines.push(`- Seed: ${String(result.seed)}, latency runs per statement: ${String(result.latencyRuns)}`);
  lines.push(
    `- Fan-out (median / max): offers per variant ` +
      `${String(result.graph.offersPerVariant.median)} / ${String(result.graph.offersPerVariant.max)}, ` +
      `variants per product ${String(result.graph.variantsPerProduct.median)} / ${String(result.graph.variantsPerProduct.max)}, ` +
      `products per brand ${String(result.graph.productsPerBrand.median)} / ${String(result.graph.productsPerBrand.max)}`,
  );
  lines.push('');

  if (violations.length > 0) {
    lines.push('## THIS RUN MEASURED NOTHING');
    lines.push('');
    lines.push(
      'The harness refuses to publish latencies it cannot vouch for. Every line below is a ' +
        'floor that was not cleared — a table that seeded short, or a read that returned no ' +
        'rows and therefore timed an empty predicate.',
    );
    lines.push('');
    for (const violation of violations) lines.push(`- ${violation}`);
    lines.push('');
    return lines.join('\n');
  }

  lines.push('## Seeded dataset');
  lines.push('');
  lines.push('| Table | Rows |');
  lines.push('| --- | ---: |');
  for (const [table, count] of [...result.rowCounts].sort((a, b) => b[1] - a[1])) {
    if (count > 0) lines.push(`| \`${table}\` | ${count.toLocaleString('en-US')} |`);
  }
  lines.push('');

  lines.push('## Shipped reads');
  lines.push('');
  lines.push(
    'Each row is a real repository function invoked against a recording connection; the SQL ' +
      'measured is the SQL that reader put on the wire. `plan exec ms` is the instrumented ' +
      '`EXPLAIN ANALYZE` execution time and is an upper bound — the percentiles come from ' +
      'uninstrumented runs and include the round trip.',
  );
  lines.push('');
  lines.push(SHAPE_TABLE_HEADER);
  for (const shape of result.shapes) lines.push(shapeRow(shape));
  lines.push('');

  lines.push('### Buffer behaviour (first touch versus steady state)');
  lines.push('');
  lines.push(
    'A genuinely cold cache is not reachable from this harness — evicting the OS page cache ' +
      'needs privileges a benchmark should not hold — so `first-touch reads` is a LOWER BOUND ' +
      'on what a cold read would cost, not a cold measurement.',
  );
  lines.push('');
  lines.push('| Shape | first-touch reads | steady hits | steady reads |');
  lines.push('| --- | ---: | ---: | ---: |');
  for (const shape of result.shapes) {
    if (shape.statementIndex !== 0) continue;
    lines.push(
      `| ${shape.shapeId} | ${String(shape.firstTouchReadBlocks)} | ` +
        `${String(shape.steadyHitBlocks)} | ${String(shape.steadyReadBlocks)} |`,
    );
  }
  lines.push('');

  lines.push('## Shapes not measured as a shipped read');
  lines.push('');
  lines.push(
    'Shapes #61 asked to compare that either no code path runs at all, or that a shipped reader ' +
      'runs only as a fragment of a statement measured whole above. Each row states which. They ' +
      'are kept in a separate table so an exploratory figure can never be quoted as a ' +
      'production latency.',
  );
  lines.push('');
  lines.push(SHAPE_TABLE_HEADER);
  for (const shape of result.exploratory) lines.push(shapeRow(shape));
  lines.push('');

  lines.push('## Write cost');
  lines.push('');
  lines.push('| Write | Reader | p50 ms | p95 ms | p99 ms |');
  lines.push('| --- | --- | ---: | ---: | ---: |');
  for (const cost of result.writeCosts) {
    lines.push(
      `| ${cost.label} | \`${cost.reader}\` | ${ms(cost.latency.p50Ms)} | ` +
        `${ms(cost.latency.p95Ms)} | ${ms(cost.latency.p99Ms)} |`,
    );
  }
  lines.push('');

  lines.push('## Relation sizes');
  lines.push('');
  lines.push('| Relation | Kind | Size |');
  lines.push('| --- | --- | ---: |');
  for (const size of result.sizes.slice(0, 40)) {
    lines.push(`| \`${size.relation}\` | ${size.kind} | ${formatBytes(size.bytes)} |`);
  }
  lines.push('');

  lines.push('## Plans');
  lines.push('');
  for (const shape of [...result.shapes, ...result.exploratory]) {
    const label =
      shape.statementCount > 1
        ? `${shape.shapeId}.${String(shape.statementIndex + 1)}`
        : shape.shapeId;
    lines.push(`### ${label} — ${shape.title}`);
    lines.push('');
    lines.push(`Reader: \`${shape.reader}\``);
    lines.push('');
    lines.push('```sql');
    lines.push(shape.sqlText.trim());
    lines.push('```');
    lines.push('');
    lines.push(
      `Node types: ${shape.analysis.nodeTypes.join(' → ')}. ` +
        `Planning ${ms(shape.analysis.planningTimeMs)} ms, execution ${ms(shape.analysis.executionTimeMs)} ms ` +
        `(instrumented). Rows scanned ${String(shape.analysis.rowsScanned)}, returned ` +
        `${String(shape.analysis.rowsReturned)}.`,
    );
    lines.push('');
  }

  return lines.join('\n');
}
